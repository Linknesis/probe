# Linknesis Windows Probe Installer
# Run as Administrator

param(
    [Parameter(Mandatory = $true)]
    [string]$CoreAddress,
    [string]$Hash = "",
    [string]$InstallDir = "C:\linknesis"
)

$ErrorActionPreference = "Stop"

function Write-Info($msg) {
    Write-Host "[INFO] $msg" -ForegroundColor Cyan
}

function Write-ErrorAndExit($msg) {
    Write-Host "[ERROR] $msg" -ForegroundColor Red
    exit 1
}

# Ensure admin privileges
$currentPrincipal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $currentPrincipal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Write-ErrorAndExit "This script must be run as Administrator."
}

# Create install directory
if (-not (Test-Path $InstallDir)) {
    New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null
}
Write-Info "Install directory: $InstallDir"

# Stop existing task if running
$taskName = "LinknesisProbe"
$existingTask = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
if ($existingTask) {
    Write-Info "Stopping existing scheduled task..."
    Stop-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
    Unregister-ScheduledTask -TaskName $taskName -Confirm:$false
}

# Stop existing process
$proc = Get-Process -Name "linknesis-probe" -ErrorAction SilentlyContinue
if ($proc) {
    Write-Info "Stopping existing linknesis-probe process..."
    $proc | Stop-Process -Force
    Start-Sleep -Seconds 1
}

# Copy binary (assumes script runs from same directory as binary)
$binarySource = Join-Path $PSScriptRoot "linknesis-probe.exe"
if (-not (Test-Path $binarySource)) {
    # Fallback: look in current directory
    $binarySource = "linknesis-probe.exe"
}
if (Test-Path $binarySource) {
    $binaryDest = Join-Path $InstallDir "linknesis-probe.exe"
    $srcFull = [System.IO.Path]::GetFullPath($binarySource)
    $dstFull = [System.IO.Path]::GetFullPath($binaryDest)
    if ($srcFull -ieq $dstFull) {
        Write-Info "Binary already in install directory"
    } else {
        Copy-Item -Path $binarySource -Destination $binaryDest -Force
        Write-Info "Copied linknesis-probe.exe"
    }
} else {
    Write-ErrorAndExit "linknesis-probe.exe not found in script directory."
}

function Safe-Copy($source, $destDir, $name) {
    if (Test-Path $source) {
        $dest = Join-Path $destDir $name
        $srcFull = [System.IO.Path]::GetFullPath($source)
        $dstFull = [System.IO.Path]::GetFullPath($dest)
        if ($srcFull -ieq $dstFull) {
            Write-Info "$name already in install directory"
        } else {
            Copy-Item -Path $source -Destination $dest -Force
            Write-Info "Copied $name"
        }
    }
}

function Ensure-IcmpFirewallRule($displayName, $icmpType, $protocol = "ICMPv4") {
    # TCP/UDP MTR depends entirely on these rules to see intermediate-hop/
    # target ICMP replies (see probe/src/mtr.zig's runWindowsMtr{Tcp,Udp}[6]);
    # a rule that silently fails to create (or gets removed later -- e.g. a
    # Windows feature upgrade, such as Windows 10 to 11, resetting custom
    # inbound rules)
    # leaves those two protocols running but effectively broken with no
    # visible error. Verify the rule actually landed in the policy store
    # rather than just trusting that the cmdlet didn't throw, and return a
    # clear pass/fail the caller can act on instead of assuming success.
    $existing = Get-NetFirewallRule -DisplayName $displayName -ErrorAction SilentlyContinue
    if ($existing) {
        Write-Info "Firewall rule already exists: $displayName"
        return $true
    }

    try {
        New-NetFirewallRule `
            -DisplayName $displayName `
            -Direction Inbound `
            -Protocol $protocol `
            -IcmpType $icmpType `
            -Action Allow `
            -Profile Any `
            -ErrorAction Stop | Out-Null
    } catch {
        Write-Host "[WARN] Failed to create firewall rule '$displayName': $($_.Exception.Message)" -ForegroundColor Yellow
        return $false
    }

    $verify = Get-NetFirewallRule -DisplayName $displayName -ErrorAction SilentlyContinue
    if (-not $verify) {
        Write-Host "[WARN] Firewall rule '$displayName' did not verify after creation" -ForegroundColor Yellow
        return $false
    }
    Write-Info "Created firewall rule: $displayName"
    return $true
}

Safe-Copy (Join-Path $PSScriptRoot "iperf3.exe") $InstallDir "iperf3.exe"
Safe-Copy (Join-Path $PSScriptRoot "cygwin1.dll") $InstallDir "cygwin1.dll"
Safe-Copy (Join-Path $PSScriptRoot "linknesis.ico") $InstallDir "linknesis.ico"

# TCP/UDP MTR depends on ICMP Time Exceeded and Destination Unreachable
# replies generated by intermediate routers and the target.
$fwOk = $true
$fwOk = (Ensure-IcmpFirewallRule "Linknesis Allow ICMPv4 Time Exceeded" 11) -and $fwOk
$fwOk = (Ensure-IcmpFirewallRule "Linknesis Allow ICMPv4 Destination Unreachable" 3) -and $fwOk
# ICMPv6 equivalents (Time Exceeded = type 3, Destination Unreachable = type 1)
# required for IPv6 TCP/UDP MTR.
$fwOk = (Ensure-IcmpFirewallRule "Linknesis Allow ICMPv6 Time Exceeded" 3 "ICMPv6") -and $fwOk
$fwOk = (Ensure-IcmpFirewallRule "Linknesis Allow ICMPv6 Destination Unreachable" 1 "ICMPv6") -and $fwOk
if (-not $fwOk) {
    Write-Host ""
    Write-Host "[WARN] One or more MTR firewall rules could not be created." -ForegroundColor Yellow
    Write-Host "       TCP/UDP MTR tests will still run but every hop before the target" -ForegroundColor Yellow
    Write-Host "       will time out (~5s each) instead of resolving normally, since they" -ForegroundColor Yellow
    Write-Host "       depend on these inbound rules to see ICMP replies. Re-run this" -ForegroundColor Yellow
    Write-Host "       installer as Administrator, or create the rules manually, e.g.:" -ForegroundColor Yellow
    Write-Host "       New-NetFirewallRule -DisplayName 'Linknesis Allow ICMPv4 Time Exceeded' -Direction Inbound -Protocol ICMPv4 -IcmpType 11 -Action Allow" -ForegroundColor Yellow
    Write-Host ""
}

# Ensure PATH contains install dir
$currentPath = [Environment]::GetEnvironmentVariable("PATH", "Machine")
if (-not ($currentPath -like "*$InstallDir*")) {
    [Environment]::SetEnvironmentVariable("PATH", "$currentPath;$InstallDir", "Machine")
    Write-Info "Added $InstallDir to system PATH"
}

# Create config.json if hash provided
if ($Hash -ne "") {
    $configPath = Join-Path $InstallDir "config.json"
    $uuid = $null
    if (Test-Path $configPath) {
        try {
            $existingConfig = Get-Content -Path $configPath -Raw | ConvertFrom-Json
            if ($existingConfig.uuid) {
                $uuid = [string]$existingConfig.uuid
            }
        } catch {
            Write-Info "Existing config.json could not be parsed; generating a new probe UUID"
        }
    }
    if (-not $uuid) {
        $uuid = [guid]::NewGuid().ToString()
    }
    $config = @{
        uuid = $uuid
        core_address = $CoreAddress
        hash = $Hash
    } | ConvertTo-Json -Compress
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($configPath, $config, $utf8NoBom)
    Write-Info "Wrote config.json with probe UUID $uuid"
}

# Create scheduled task for auto-start with highest privileges
$action = New-ScheduledTaskAction -Execute (Join-Path $InstallDir "linknesis-probe.exe") -WorkingDirectory $InstallDir
$trigger = New-ScheduledTaskTrigger -AtLogOn
$userName = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
$principal = New-ScheduledTaskPrincipal -UserId $userName -RunLevel Highest
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -RunOnlyIfNetworkAvailable:$false -ExecutionTimeLimit (New-TimeSpan -Seconds 0)

Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Principal $principal -Settings $settings -Force | Out-Null
Write-Info "Registered scheduled task '$taskName'"

# Start the task
Start-ScheduledTask -TaskName $taskName
Write-Info "Started Linknesis Probe"

Write-Host ""
Write-Host "Installation complete." -ForegroundColor Green
Write-Host "The probe is running from: $InstallDir" -ForegroundColor Green
Write-Host "Configuration file: $(Join-Path $InstallDir 'config.json')" -ForegroundColor Green
Write-Host "Logs: $(Join-Path $InstallDir 'linknesis-debug.log')" -ForegroundColor Green
Write-Host ""
Write-Host "To manage the task:" -ForegroundColor Yellow
Write-Host "  Start:  schtasks /run /tn $taskName" -ForegroundColor Yellow
Write-Host "  Stop:   schtasks /end /tn $taskName" -ForegroundColor Yellow
Write-Host "  Query:  schtasks /query /tn $taskName" -ForegroundColor Yellow
